// Toolbar (from r13): roving focus, seams, toggles, the exclusive band, the docked menu, the panel cell with its
// input, the vertical toolbar, the narrow row's scroll edges, and RTL.
import { test, idle } from "./fixtures.mjs"
import { poll, near, css, box, token, stableBox } from "./lib/probes-c.mjs"
// the specimen entries these tests use (fixtures.mjs: only)
test.use({ only: ["toolbar"] })

const focusedName = (p) => p.evaluate(() => { const a = document.activeElement; return a?.getAttribute("aria-label") || a?.textContent?.trim() || a?.tagName })
const READY = "[data-testid=specimen-toolbar]"

test("toolbar: editor row — roving focus, seams, toggles, band, spacer, docked menu", async ({ open, ok }) => {
  const p = await open({ ready: READY })
  const tb = p.getByTestId("tb-editor")
  await tb.scrollIntoViewIfNeeded()
  ok("toolbar: role toolbar, named, horizontal", (await tb.getAttribute("role")) === "toolbar" && (await tb.getAttribute("aria-label")) === "Formatting" && (await tb.getAttribute("aria-orientation")) === "horizontal", null)
  const stops = await tb.evaluate((t) => [...t.querySelectorAll("button, a, input")].filter((e) => e.tabIndex === 0).length)
  ok("toolbar: one Tab stop (roving tabindex)", stops === 1, stops)
  await tb.getByRole("button", { name: "Undo" }).focus()
  await p.keyboard.press("ArrowRight")
  ok("toolbar: ArrowRight reaches the disabled Redo (disabled items stay focusable)", (await focusedName(p)) === "Redo" && (await p.evaluate(() => document.activeElement.getAttribute("aria-disabled") === "true" || document.activeElement.hasAttribute("data-disabled"))), await focusedName(p))
  await p.keyboard.press("ArrowRight")
  ok("toolbar: arrows cross into a toggle group", (await focusedName(p)) === "Bold", await focusedName(p))
  const stops2 = await tb.evaluate((t) => [...t.querySelectorAll("button, a, input")].filter((e) => e.tabIndex === 0).map((e) => e.getAttribute("aria-label")))
  ok("toolbar: the roving stop follows focus", stops2.length === 1 && stops2[0] === "Bold", stops2)
  const ring = await p.evaluate(() => { const c = getComputedStyle(document.activeElement); return { off: c.outlineOffset, w: c.outlineWidth, s: c.outlineStyle } })
  ok("toolbar: the focused item shows one ring inside its cell (ring-in)", parseFloat(ring.off) < 0 && ring.s === "solid" && parseFloat(ring.w) >= 2, ring)
  await tb.getByRole("button", { name: "Undo" }).focus()
  await p.keyboard.press("ArrowLeft")
  ok("toolbar: arrows wrap: ArrowLeft from the first item reaches the last", (await focusedName(p)) === "Publish", await focusedName(p))
  await p.keyboard.press("ArrowRight")
  ok("toolbar: …and ArrowRight from the last returns to the first", (await focusedName(p)) === "Undo", await focusedName(p))

  // seams: 1px between items, 2px at a group's edge
  const g = await tb.evaluate((t) => {
    const redo = t.querySelector('[aria-label="Redo"]'), style = t.querySelector('[aria-label="Text style"]'), italic = t.querySelector('[aria-label="Italic"]')
    return { redo: getComputedStyle(redo).borderInlineStartWidth, group: getComputedStyle(style).borderInlineStartWidth, inGroup: getComputedStyle(italic).borderInlineStartWidth, frame: getComputedStyle(t).borderTopWidth }
  })
  ok("toolbar: items share 1px seams; a group meets its neighbour on 2px; the frame is 2px", g.redo === "1px" && g.inGroup === "1px" && g.group === "2px" && g.frame === "2px", g)
  const sq = await box(tb.getByRole("button", { name: "Bold" }))
  ok("toolbar: a glyph item is square", near(sq.w, sq.h, 1.5), sq)

  // independent toggle: Bold starts pressed (yellow flood); Space releases it
  const bold = tb.getByRole("button", { name: "Bold" })
  const yellow = await token(p, "--kl-yellow")
  await idle(p) // the focus moves above may have started colour transitions
  const boldBg = await poll(() => css(bold, "background-color"), (c) => c === yellow, 2000)
  ok("toolbar: a pressed toggle floods the working signal", (await bold.getAttribute("aria-pressed")) === "true" && boldBg === yellow, boldBg)
  await bold.focus()
  await p.keyboard.press("Space")
  const logText = await poll(() => p.getByTestId("tb-log").textContent(), (t) => /style none/.test(t))
  ok("toolbar: Space toggles; state and log follow", (await bold.getAttribute("aria-pressed")) === "false" && /style none/.test(logText), logText)
  const comments = tb.getByRole("button", { name: /Comments/ })
  ok("toolbar: a labelled toggle's lamp is solid while pressed", (await css(comments.locator(".kl-lamp"), "border-top-width")) === "5px", await css(comments.locator(".kl-lamp"), "border-top-width"))
  await comments.click()
  await poll(() => comments.getAttribute("aria-pressed"), (v) => v === "false")
  await idle(p)
  const lamp = await poll(() => css(comments.locator(".kl-lamp"), "border-top-width"), (v) => v === "2px", 2000)
  ok("toolbar: …and hollow when released", lamp === "2px" && (await comments.getAttribute("aria-pressed")) === "false", null)

  // exclusive group: the ink band stretches to the chosen cell
  const centre = tb.getByRole("button", { name: "Align centre" })
  await centre.click()
  const bandOf = () => tb.evaluate((t) => { const b = t.querySelector(".kl-tb-band").getBoundingClientRect(), c = t.querySelector('[aria-label="Align centre"]').getBoundingClientRect(); return { dx: Math.abs(b.x - c.x), dw: Math.abs(b.width - c.width), hidden: t.querySelector(".kl-tb-band").hidden } })
  await idle(p)
  await stableBox(tb.locator(".kl-tb-band"))
  const band = await poll(bandOf, (b) => !b.hidden && b.dx < 2 && b.dw < 3, 2000)
  ok("toolbar: exclusive choice moves the ink band onto the chosen cell", !band.hidden && band.dx < 2 && band.dw < 3, band)
  ok("toolbar: exclusive choice: one pressed, text flipped, no lamp", (await centre.getAttribute("aria-pressed")) === "true" && (await tb.getByRole("button", { name: "Align start" }).getAttribute("aria-pressed")) === "false" && (await centre.getAttribute("data-kl-covered")) !== null && (await centre.locator(".kl-lamp").count()) === 0, null)
  const primary = tb.getByRole("button", { name: "Publish" })
  ok("toolbar: the primary item is the commit (cobalt) cell", (await css(primary, "background-color")) === (await token(p, "--kl-cobalt")), await css(primary, "background-color"))

  // spacer
  const sp = await tb.locator(".kl-tb-spacer").evaluate((e) => ({ w: e.getBoundingClientRect().width, hidden: e.getAttribute("aria-hidden"), tab: e.tabIndex }))
  ok("toolbar: the spacer is an inert empty cell that takes the free space", sp.w > 40 && sp.hidden === "true" && sp.tab < 0, sp)

  // menu docked to the frame
  const insert = tb.getByRole("button", { name: "Insert" })
  await insert.click()
  const menu = p.locator('[data-slot="toolbar-menu"]')
  await menu.waitFor({ state: "visible" })
  await idle(p)
  await stableBox(menu)
  const tbb = await box(tb), mb = await box(menu), ib = await box(insert)
  ok("toolbar: the menu's top border lies on the toolbar's bottom keyline (one 2px edge)", near(mb.y, tbb.b - 2, 1) && (await css(menu, "border-top-width")) === "2px", { menuTop: mb.y, tbBottom: tbb.b })
  ok("toolbar: the menu starts at its title", near(mb.x, ib.x, 2.5), { m: mb.x, t: ib.x })
  const inv = await token(p, "--kl-inverse")
  const insBg = await poll(() => css(insert, "background-color"), (c) => c === inv, 2000)
  ok("toolbar: the open title is the inverse cell", insBg === inv, insBg)
  await p.keyboard.press("Escape")
  await poll(async () => (await menu.count()) === 0 || !(await menu.isVisible()))
  ok("toolbar: Escape closes the menu and returns focus to its title", (await menu.count()) === 0 || !(await menu.isVisible()), null)
  ok("toolbar: …focus is on Insert", (await focusedName(p)) === "Insert", await focusedName(p))
  ok("toolbar: no page errors", p.errs.length === 0, p.errs)
})

test("toolbar cell: panel — separator, filler, input caret, docked menu", async ({ open, ok }) => {
  const p = await open({ ready: READY })
  // panel cell: input, separator, link, filler and the body's keyline
  const pt = p.getByTestId("tb-panel").getByRole("toolbar")
  await pt.scrollIntoViewIfNeeded()
  const pg = await pt.evaluate((t) => {
    const sep = t.querySelector(".kl-tb-sep"), after = sep.nextElementSibling, body = t.nextElementSibling
    return { frame: getComputedStyle(t).borderTopWidth, sep: getComputedStyle(sep).borderInlineStartWidth, sepRole: sep.getAttribute("role"), afterSep: getComputedStyle(after).borderInlineStartWidth, filler: parseFloat(getComputedStyle(t, "::after").width) || 0, fillerSeam: getComputedStyle(t, "::after").borderInlineStartWidth, body: getComputedStyle(body).borderTopWidth }
  })
  ok("toolbar cell: no frame of its own; the panel body owns the 1px keyline under it", pg.frame === "0px" && pg.body === "1px", pg)
  ok("toolbar cell: the separator is a 2px keyline, announced; the item after it draws no second edge", pg.sep === "2px" && pg.sepRole === "separator" && pg.afterSep === "0px", pg)
  ok("toolbar cell: an empty filler cell closes the last item (its seam)", pg.filler > 20 && pg.fillerSeam === "1px", pg)
  const input = pt.getByRole("textbox", { name: "Search records" })
  await input.click()
  await p.keyboard.type("Rotterdam")
  await p.keyboard.press("ArrowLeft")
  ok("toolbar input: ArrowLeft moves the caret inside text, focus stays", (await focusedName(p)) !== "Columns" && (await input.evaluate((e) => e === document.activeElement && e.selectionStart === 8)), await input.evaluate((e) => e.selectionStart))
  await p.keyboard.press("ArrowRight")
  await p.keyboard.press("ArrowRight")
  ok("toolbar input: at the text's end ArrowRight moves to the next item", (await focusedName(p)) === "Columns", await focusedName(p))
  const edgeOf = () => pt.locator(".kl-tb-input").evaluate((e) => { e.querySelector("input").focus(); return getComputedStyle(e, "::before").borderTopWidth })
  const edge = await poll(edgeOf, (v) => parseFloat(v) >= 2, 2000)
  ok("toolbar input: focus is the cell's own edge band (kl-edge)", parseFloat(edge) >= 2, edge)
  await pt.getByRole("button", { name: "Columns" }).click()
  const cm = p.locator('[data-slot="toolbar-menu"]')
  await cm.waitFor({ state: "visible" })
  ok("toolbar cell: its menu docks at cell weight (1px)", (await css(cm, "border-top-width")) === "1px", await css(cm, "border-top-width"))
  await p.getByRole("menuitemcheckbox", { name: "Weight" }).click()
  const panelText = await poll(() => p.getByTestId("tb-panel").textContent(), (t) => /weight/.test(t), 2000)
  ok("toolbar cell: menu checkbox items keep the menu open and reach state", (await cm.isVisible()) && /weight/.test(panelText), null)
  await p.keyboard.press("Escape")
  ok("toolbar: no page errors", p.errs.length === 0, p.errs)
})

