test("toolbar RTL: arrows follow reading order, row and menu mirror", async ({ open, ok }) => {
  const p = await open({ q: "dir=rtl", ready: READY })
  const tb = p.getByTestId("tb-editor")
  await tb.getByRole("button", { name: "Undo" }).focus()
  await p.keyboard.press("ArrowLeft")
  ok("toolbar RTL: ArrowLeft moves forward (reading order)", (await focusedName(p)) === "Redo", await focusedName(p))
  const r = await tb.evaluate((t) => { const u = t.querySelector('[aria-label="Undo"]').getBoundingClientRect(), pub = [...t.querySelectorAll("button")].find((x) => x.textContent.includes("Publish")).getBoundingClientRect(); return u.x > pub.x })
  ok("toolbar RTL: the row mirrors (first item at the right)", r, null)
  await tb.getByRole("button", { name: "Insert" }).click()
  const menu = p.locator('[data-slot="toolbar-menu"]')
  await menu.waitFor({ state: "visible" })
  await idle(p)
  await stableBox(menu)
  const mb = await box(menu), ib = await box(tb.getByRole("button", { name: "Insert" }))
  ok("toolbar RTL: the menu aligns to its title's start (right) edge", near(mb.r, ib.r, 2.5), { m: mb.r, t: ib.r })
  await p.keyboard.press("Escape")
  ok("toolbar RTL: no page errors", p.errs.length === 0, p.errs)
})
