// Generates the theme's CSS from its single source:
//   src/registry/keyline/theme/tokens.ts + foundation.css  ->  theme/keyline.css
//   src/registry/keyline/theme/tokens.ts                   ->  theme/keyline-shadcn.css
// `pnpm registry:build` runs it before the build; tests/registry/rebuild.test.ts fails when the committed files
// differ from what it generates. generateTheme() is pure; run as a script, it writes the two files.
import { readFileSync, writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";

import {
  CONSTANTS,
  CUT,
  CUT_DEFAULT,
  DENSITIES,
  MOTION,
  MOTION_REDUCED,
  RHYTHM,
  SHADCN_MAP,
  SOURCES,
  TEXT,
  THEME_ENTRIES,
  TYPE,
  Z,
  type Density,
  type Token,
} from "../../src/registry/keyline/theme/tokens.ts";

const ROOT = new URL("../..", import.meta.url).pathname;
export const THEME_DIR = "src/registry/keyline/theme/";

const decl = (indent: string, [name, value, note]: Token) =>
  `${note ? `${indent}/* ${note} */\n` : ""}${indent}--kl-${name}: ${value};`;
const block = (indent: string, selector: string, tokens: readonly Token[]) =>
  `${indent}${selector} {\n${tokens.map((t) => decl(indent + "  ", t)).join("\n")}\n${indent}}`;
const densityTokens = (d: Density): Token[] => [
  ...Object.entries(RHYTHM[d]).map(([k, v]) => [k, v] as const),
  ...Object.entries(TEXT[d]).map(([k, v]) => [`text-${k}`, v] as const),
];

const GENERATED = (from: string) =>
  `/* GENERATED by scripts/registry/theme.ts from ${from} (pnpm registry:build). Do not edit this file. */`;

function keylineCss(foundation: string) {
  const theme = THEME_ENTRIES.map(([entry, token]) => `  --${entry}: var(--kl-${token});`).join("\n");
  const sources = SOURCES.map((t) => decl("  ", t)).join("\n");
  return `${GENERATED("theme/tokens.ts and theme/foundation.css")}
/* Keyline theme: tokens and shared construction. The \`keyline\` registry item (a registry:theme).
   Coexistence rule: it defines only --kl-* tokens, kl- classes and data-kl-* scopes. Mapping shadcn's tokens,
   radius, fonts and body to Keyline is opt-in: keyline-shadcn.css (registry item \`keyline-shadcn\`). */

${TYPE.packages.map((p) => `@import "${p}";`).join("\n")}

/* TAILWIND UTILITIES: every colour role as a Tailwind colour of the same name (bg-kl-cell, text-kl-ink-2,
   border-kl-seam), the type voices and weights (font-kl-mono, font-kl-strong), geometry and rhythm as spacing
   (h-kl-ctl, px-kl-inset, gap-kl-gutter), the type scale (text-kl-label) and the eases. Prefixed kl- so shadcn's
   own utilities are untouched. \`inline\` is required: a plain @theme resolves var(--kl-cell) once on :root, and a
   .dark subtree or a [data-kl-config] scope would paint the page's colours. */
@theme inline {
${theme}
}

/* SOURCES: the configurable tokens. \`shadcn add\` writes these two blocks into the app's own :root and .dark
   (cssVars), where they are edited; re-adding the keyline item updates them. Everything in the DERIVED block is
   computed from them, so changing one source colour updates its fills, foregrounds, text variants, focus,
   selection and data colours, in both themes. A [data-kl-config] scope sets them for a subtree; portaled
   overlays copy the sources of the place they were written (lib/keyline-scope). */
:root {
${sources}
}
.dark {
  --kl-dark: 1;
}

/* TOKENS a data-kl-* scope overrides, on any element including <html>: layered, so the scope's attribute wins
   over these defaults wherever it is set, and a consumer's own unlayered CSS wins over both. */
@layer base {
${block("  ", ":root", [
  [
    "cut",
    CUT_DEFAULT,
    "0 off, 0.5 quiet, 1 full; inherits, set on any subtree. Square by default: the cut is an accent",
  ],
  ...densityTokens("default"),
  ...CONSTANTS,
  ...MOTION,
  ...Z,
])}
  .light {
    --kl-dark: 0;
  }
${Object.entries(CUT)
  .map(([k, v]) => block("  ", `[data-kl-cut="${k}"]`, [["cut", v]]))
  .join("\n")}
${DENSITIES.map((d) => block("  ", `[data-kl-density="${d}"]`, densityTokens(d))).join("\n")}
${block("  ", '[data-kl-motion="reduce"]', MOTION_REDUCED)}
  @media (prefers-reduced-motion: reduce) {
${block("    ", ":root", MOTION_REDUCED)}
  }
}

${foundation.replace(/^\/\*[\s\S]*?\*\/\n\n/, "")}`;
}

function shadcnCss() {
  const map = SHADCN_MAP.map(([k, role]) => `  --${k}: var(--kl-${role});`).join("\n");
  return `${GENERATED("theme/tokens.ts (SHADCN_MAP)")}
/* Opt-in: make the whole app Keyline, including stock shadcn components. Maps shadcn's semantic tokens, radius,
   fonts and the page body to Keyline tokens. The \`keyline-shadcn\` registry item; requires the \`keyline\` item.
   The mapping is stated for :root and .light, for .dark (replacing shadcn's own dark values) and for every
   configuration scope, where var() must resolve against the scope's own Keyline tokens. */

:root,
.light {
${map}
  /* here, not in a layer: the CLI writes this block into the app's own :root, replacing shadcn's 0.625rem */
  --radius: 0px;
}

.dark {
${map}
}

[data-kl-config] {
${map}
}

/* --chart-* is left to the app: Keyline's data colours are roles (--kl-data-1…3, mark, alert), not a series */

@theme inline {
  --font-sans: var(--kl-font);
  --font-mono: var(--kl-font-mono);
  /* Tailwind's own \`--radius: 0.25rem\` is inline, so the bare \`rounded\` utility needs this too, not only :root */
  --radius: 0px;
}

@layer base {
  /* native controls and scrollbars follow the theme; layered, so an app's own color-scheme still wins */
  :root,
  .light {
    color-scheme: light;
  }
  .dark {
    color-scheme: dark;
  }
  body {
    background-color: var(--kl-paper);
    color: var(--kl-ink);
    font-family: var(--kl-font);
    font-size: var(--kl-fs);
    line-height: 1.4;
    font-variant-numeric: tabular-nums;
    -webkit-font-smoothing: antialiased;
  }
  :focus-visible {
    outline: 2px solid var(--kl-focus);
    outline-offset: 2px;
  }
}
`;
}

/** The generated files, keyed by repo-relative path. */
export function generateTheme(): Map<string, string> {
  const foundation = readFileSync(ROOT + THEME_DIR + "foundation.css", "utf8");
  return new Map([
    [THEME_DIR + "keyline.css", keylineCss(foundation)],
    [THEME_DIR + "keyline-shadcn.css", shadcnCss()],
  ]);
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  for (const [file, css] of generateTheme()) writeFileSync(ROOT + file, css);
  console.log(`theme: wrote ${[...generateTheme().keys()].join(", ")}`);
}
