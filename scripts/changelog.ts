// The changelog has one source: each item's `changelog[]` in its .meta.ts. This turns it into
//   CHANGELOG.md               dated, newest first, for the repository;
//   site/lib/changelog.json    the same entries for the site: /docs/changelog by date, and each item's own history.
//
//   pnpm changelog          writes both
//   pnpm changelog:check    fails when either differs from what the metas generate
//
// A breaking entry carries coss's template (src/registry/item.ts, Migration): what changed (the note), the diff for a
// project that uses the item, the re-add command (generated here), the diff for a locally modified copy, and a
// prompt for an agent. Its line starts with **Breaking:**.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { pathToFileURL } from "node:url";

import { loadMetas, ROOT } from "./registry/build.ts";
import type { ChangelogEntry, Migration } from "../src/registry/item.ts";

export const MARKDOWN = "CHANGELOG.md";
export const DATA = "site/lib/changelog.json";

export type Entry = {
  item: string;
  version: string;
  note: string;
  breaking: boolean;
  /** For a breaking entry: coss's template, with the re-add command filled in. */
  migration?: Migration & { readd: string };
};
export type ChangelogData = {
  /** Newest date first; within a date, breaking entries first, then by item name. */
  releases: { date: string; entries: Entry[] }[];
  /** Each item's history, newest first: the "Changelog" section of its page. */
  items: Record<string, (Entry & { date: string })[]>;
};

const readd = (item: string) => `npx shadcn@latest add @keyline-ui/${item}`;

function entry(item: string, e: ChangelogEntry): Entry {
  return {
    item,
    version: e.version,
    note: e.note,
    breaking: e.breaking === true,
    ...(e.breaking === true ? { migration: { ...e.migration, readd: readd(item) } } : {}),
  };
}

export async function changelogData(): Promise<ChangelogData> {
  const metas = await loadMetas();
  const byDate = new Map<string, Entry[]>();
  const items: ChangelogData["items"] = {};
  for (const m of metas) {
    items[m.name] = m.changelog.map((e) => ({ ...entry(m.name, e), date: e.date }));
    for (const e of m.changelog) byDate.set(e.date, [...(byDate.get(e.date) ?? []), entry(m.name, e)]);
  }
  const releases = [...byDate]
    .toSorted(([a], [b]) => (a < b ? 1 : a > b ? -1 : 0))
    .map(([date, entries]) => ({
      date,
      entries: entries.toSorted(
        (a, b) => Number(b.breaking) - Number(a.breaking) || (a.item < b.item ? -1 : a.item > b.item ? 1 : 0),
      ),
    }));
  return { releases, items };
}

const fence = (lang: string, body: string) => `\`\`\`${lang}\n${body.trimEnd()}\n\`\`\``;

export function markdown(data: ChangelogData): string {
  const out = [
    "# Changelog",
    "",
    "Keyline ships through the shadcn registry, so each item has its own version (`/r/versions.json` publishes them).",
    "Entries are dated, newest first. A breaking entry starts with **Breaking:** and says how to migrate code you",
    "already copied.",
    "",
    "Generated by `pnpm changelog` from each item's `changelog[]` in its `.meta.ts`. Do not edit it by hand.",
  ];
  for (const { date, entries } of data.releases) {
    out.push("", `## ${date}`, "");
    for (const e of entries)
      out.push(
        `- **${e.item}** ${e.version}: ${e.breaking ? "**Breaking:** " : ""}${e.note.trim().replace(/\s+/g, " ")}`,
      );
    for (const e of entries.filter((x) => x.migration)) {
      const m = e.migration!;
      out.push(
        "",
        `### ${e.item} ${e.version}: migration`,
        "",
        fence("diff", m.diff),
        "",
        "Re-add it:",
        "",
        fence("sh", m.readd),
        "",
        "If you keep a locally modified copy:",
        "",
        fence("diff", m.modified),
        "",
        "Agent prompt:",
        "",
        fence("text", m.prompt),
      );
    }
  }
  return out.join("\n") + "\n";
}

async function main() {
  const data = await changelogData();
  const files: [string, string][] = [
    [MARKDOWN, markdown(data)],
    [DATA, JSON.stringify(data, null, 2) + "\n"],
  ];
  if (process.argv.includes("--check")) {
    const stale = files.filter(([f, txt]) => !existsSync(ROOT + f) || readFileSync(ROOT + f, "utf8") !== txt);
    for (const [f] of stale) console.error(`changelog: ${f} is not what the metas generate; run pnpm changelog`);
    if (stale.length) process.exitCode = 1;
    else console.log(`changelog: ${files.map(([f]) => f).join(", ")} match the metas`);
    return;
  }
  for (const [f, txt] of files) writeFileSync(ROOT + f, txt);
  console.log(`changelog: wrote ${files.map(([f]) => f).join(", ")}`);
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href)
  main().catch((e: unknown) => {
    console.error(e);
    process.exitCode = 1;
  });
